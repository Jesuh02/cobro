INSERT INTO rol_recurso (rol_id, recurso_id)
SELECT r.rol_id, rec.recurso_id
FROM rol r
JOIN recurso rec ON rec.codigo = r.codigo
WHERE r.codigo IN (
  'CREAR_CAJA_MENOR',
  'REGISTRAR_FLUJO_CAJA',
  'CREAR_CREDITOS',
  'REFINANCIAR_CREDITOS',
  'AGREGAR_CUOTA'
)
ON CONFLICT DO NOTHING;

INSERT INTO rol_recurso (rol_id, recurso_id)
SELECT admin.rol_id, rec.recurso_id
FROM rol admin
JOIN recurso rec ON rec.codigo IN (
  'CREAR_CAJA_MENOR',
  'REGISTRAR_FLUJO_CAJA',
  'CREAR_CREDITOS',
  'REFINANCIAR_CREDITOS',
  'AGREGAR_CUOTA'
)
WHERE admin.codigo = 'ADMINISTRADOR'
ON CONFLICT DO NOTHING;

INSERT INTO usuario_rol (usuario_id, rol_id)
SELECT cobrador.usuario_id, permiso.rol_id
FROM usuario_rol cobrador
JOIN rol rol_base
  ON rol_base.rol_id = cobrador.rol_id
 AND rol_base.codigo = 'COBRADOR'
JOIN rol permiso
  ON permiso.codigo IN (
    'CREAR_CAJA_MENOR',
    'REGISTRAR_FLUJO_CAJA',
    'CREAR_CREDITOS',
    'REFINANCIAR_CREDITOS',
    'AGREGAR_CUOTA'
  )
ON CONFLICT DO NOTHING;
