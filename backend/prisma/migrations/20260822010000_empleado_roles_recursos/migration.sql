CREATE TABLE IF NOT EXISTS recurso (
  recurso_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(60) NOT NULL UNIQUE,
  nombre VARCHAR(120) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rol_recurso (
  rol_id SMALLINT NOT NULL REFERENCES rol (rol_id) ON DELETE CASCADE,
  recurso_id SMALLINT NOT NULL REFERENCES recurso (recurso_id) ON DELETE CASCADE,
  asignado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (rol_id, recurso_id)
);

