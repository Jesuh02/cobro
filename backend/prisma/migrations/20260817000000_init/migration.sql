-- DDL profesional para una app de préstamos, cobros por ruta, caja menor
-- y presupuesto operativo.
--
-- Motor objetivo: PostgreSQL 14+
-- Normalización: 4FN. Las dependencias transitivas se resuelven con
-- catálogos y claves foráneas; las dependencias multivaluadas se separan en
-- tablas puente o tablas hijas independientes.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS public;

COMMENT ON SCHEMA public IS
  'Modelo 4FN para préstamos, rutas de cobro, pagos, caja menor y presupuesto.';

SET search_path TO public;

CREATE OR REPLACE FUNCTION actualizar_fecha_modificacion()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.actualizado_en = now();
  RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS moneda (
  codigo_moneda CHAR(3) PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  simbolo VARCHAR(8) NOT NULL,
  decimales SMALLINT NOT NULL DEFAULT 2,
  CONSTRAINT chk_moneda_codigo_mayuscula
    CHECK (codigo_moneda = upper(codigo_moneda)),
  CONSTRAINT chk_moneda_decimales
    CHECK (decimales BETWEEN 0 AND 6)
);

CREATE TABLE IF NOT EXISTS estado_usuario (
