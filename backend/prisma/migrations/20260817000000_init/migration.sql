  pago_aplicacion_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  pago_id UUID NOT NULL REFERENCES pago (pago_id) ON DELETE CASCADE,
  credito_cuota_id UUID NOT NULL
    REFERENCES credito_cuota (credito_cuota_id) ON DELETE RESTRICT,
  monto_capital NUMERIC(14, 2) NOT NULL DEFAULT 0,
  monto_interes NUMERIC(14, 2) NOT NULL DEFAULT 0,
  monto_mora NUMERIC(14, 2) NOT NULL DEFAULT 0,
  monto_descuento NUMERIC(14, 2) NOT NULL DEFAULT 0,
  UNIQUE (pago_id, credito_cuota_id),
  CONSTRAINT chk_pago_aplicacion_montos
    CHECK (
      monto_capital >= 0
      AND monto_interes >= 0
