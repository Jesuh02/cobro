  CONSTRAINT chk_frecuencia_pago_dias
    CHECK (dias_intervalo > 0)
);

CREATE TABLE IF NOT EXISTS estado_credito (
  estado_credito_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
